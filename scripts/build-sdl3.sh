#!/usr/bin/env bash
# Build the vendored SDL3 without CMake: explicit source list + generated
# SDL_build_config.h. desktop -> static libSDL3.a, android <abi> -> libSDL3.so.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
sdl="$root/deps/SDL3-3.2.28"
target=${1:-desktop}
abi=${2:-arm64-v8a}

if [[ "$target" == android ]]; then
  if [[ -z "${ANDROID_NDK:-}" ]]; then
    ANDROID_NDK=$(ls -d "$HOME/Android/sdk/ndk/"* 2>/dev/null | sort -V | tail -1)
  fi
  [[ -n "${ANDROID_NDK:-}" ]] || { echo "ANDROID_NDK not found" >&2; exit 1; }
  if [[ "$abi" == arm64-v8a ]]; then triple=aarch64-linux-android29; else triple=x86_64-linux-android29; fi
  cc="$ANDROID_NDK/toolchains/llvm/prebuilt/linux-x86_64/bin/clang --target=$triple --sysroot=$ANDROID_NDK/toolchains/llvm/prebuilt/linux-x86_64/sysroot"
  out_dir=$root/build/android/$abi
else
  cc="clang"
  out_dir=$root/build/desktop
fi
mkdir -p "$out_dir"

# SDL_build_config.h: flatten the CMake template, enabling only what our
# source list needs
defines_common="SDL_AUDIO_DRIVER_DUMMY SDL_THREAD_PTHREAD SDL_THREAD_PTHREAD_RECURSIVE_MUTEX SDL_THREAD_PTHREAD_RECURSIVE_MUTEX_NP SDL_TIMER_UNIX SDL_GPU_DISABLED SDL_RENDER_DISABLED SDL_HAPTIC_DISABLED SDL_HIDAPI_DISABLED SDL_SENSOR_DISABLED SDL_CAMERA_DISABLED SDL_DIALOG_DISABLED SDL_JOYSTICK_DISABLED SDL_INPUT_LINUXEV SDL_TIME_UNIX SDL_FSOPS_POSIX HAVE_LINUX_INPUT_H HAVE_CLOCK_GETTIME HAVE_LIBC HAVE_STDIO_H HAVE_STDLIB_H HAVE_STRING_H HAVE_STDDEF_H HAVE_ERRNO_H HAVE_MATH_H HAVE_LIMITS_H HAVE_INTTYPES_H HAVE_STDINT_H HAVE_STRINGS_H HAVE_SIGNAL_H HAVE_FLOAT_H HAVE_STDARG_H HAVE_CTYPE_H HAVE_TIME_H HAVE_SYS_TYPES_H HAVE_DLOPEN HAVE_GETENV"
if [[ "$target" == android ]]; then
  defines="$defines_common SDL_VIDEO_DRIVER_ANDROID SDL_VIDEO_OPENGL_EGL SDL_FILESYSTEM_ANDROID SDL_LOADSO_DLOPEN SDL_TRAY_DUMMY"
else
  defines="$defines_common SDL_VIDEO_DRIVER_X11 SDL_VIDEO_DRIVER_DUMMY SDL_VIDEO_OPENGL SDL_VIDEO_OPENGL_GLX SDL_FILESYSTEM_UNIX SDL_LOADSO_DLOPEN SDL_POWER_LINUX SDL_PROCESS_POSIX SDL_JOYSTICK_LINUX SDL_JOYSTICK_DUMMY SDL_DIALOG_DUMMY SDL_LOCALE_UNIX SDL_MISC_UNIX SDL_TRAY_UNIX SDL_STORAGE_GENERIC HAVE_X11_XLIB_H SDL_VIDEO_DRIVER_X11_SUPPORTS_GENERIC_EVENTS"
fi
python3 - "$defines" "$sdl/include/build_config/SDL_build_config.h.cmake" "$out_dir/SDL_build_config.h" <<'PY'
import re, sys
defines = set(sys.argv[1].split())
tmpl = open(sys.argv[2]).read()
out = []
for line in tmpl.split('\n'):
    s = line.strip()
    if s.startswith('#cmakedefine '):
        name = s.split()[1]
        out.append(f'#define {name} 1' if name in defines else f'/* #undef {name} */')
    elif s.startswith('#cmakedefine01 '):
        name = s.split()[1]
        out.append(f'#define {name} ' + ('1' if name in defines else '0'))
    else:
        out.append(line)
txt = re.sub(r'@[^@\n]+@', '', '\n'.join(out))
present = set(re.findall(r'#define (\w+) 1', txt))
extra = ''.join(f'#define {d} 1\n' for d in sorted(defines - present))
open(sys.argv[3], 'w').write('/* Generated by scripts/build-sdl3.sh */\n' + extra + txt)
PY

# source list (linux / android backends only)
sources=(
  "$sdl"/src/*.c
  "$sdl"/src/atomic/*.c
  "$sdl"/src/audio/*.c "$sdl"/src/audio/dummy/*.c
  "$sdl"/src/cpuinfo/*.c
  "$sdl"/src/dynapi/*.c
  "$sdl"/src/events/*.c
  "$sdl"/src/io/*.c "$sdl"/src/io/generic/*.c
  "$sdl"/src/joystick/*.c "$sdl"/src/joystick/dummy/*.c
  "$sdl"/src/libm/*.c
  "$sdl"/src/loadso/dlopen/*.c
  "$sdl"/src/stdlib/*.c
  "$sdl"/src/thread/SDL_thread.c "$sdl"/src/thread/pthread/*.c
  "$sdl"/src/time/SDL_time.c "$sdl"/src/time/unix/*.c
  "$sdl"/src/timer/*.c "$sdl"/src/timer/unix/*.c
  "$sdl"/src/video/*.c "$sdl"/src/video/yuv2rgb/yuv_rgb_std.c
  "$sdl"/src/filesystem/SDL_filesystem.c "$sdl"/src/filesystem/posix/*.c
  "$sdl"/src/storage/SDL_storage.c "$sdl"/src/storage/generic/*.c
  "$sdl"/src/gpu/*.c
  "$sdl"/src/render/SDL_render.c "$sdl"/src/render/SDL_render_unsupported.c "$sdl"/src/render/SDL_yuv_sw.c
  "$sdl"/src/render/opengl/*.c "$sdl"/src/render/opengles2/*.c "$sdl"/src/render/software/*.c "$sdl"/src/render/gpu/*.c
  "$sdl"/src/haptic/SDL_haptic.c "$sdl"/src/haptic/dummy/*.c "$sdl"/src/haptic/linux/*.c "$sdl"/src/sensor/SDL_sensor.c "$sdl"/src/sensor/dummy/*.c "$sdl"/src/camera/SDL_camera.c
  "$sdl"/src/dialog/SDL_dialog.c "$sdl"/src/dialog/SDL_dialog_utils.c
  "$sdl"/src/main/SDL_main_callbacks.c "$sdl"/src/main/SDL_runapp.c "$sdl"/src/main/generic/SDL_sysmain_callbacks.c
  "$sdl"/src/core/SDL_core_unsupported.c
  "$sdl"/src/hidapi/SDL_hidapi.c
  "$sdl"/src/core/unix/SDL_poll.c "$sdl"/src/core/unix/SDL_appid.c
)
if [[ "$target" == android ]]; then
  sources+=( "$sdl"/src/core/android/SDL_android.c "$sdl"/src/video/android/*.c
             "$sdl"/src/filesystem/android/*.c "$sdl"/src/misc/android/*.c
             "$sdl"/src/tray/SDL_tray_utils.c "$sdl"/src/tray/dummy/SDL_tray.c )
else
  sources+=( "$sdl"/src/core/linux/SDL_threadprio.c
             "$sdl"/src/core/linux/SDL_evdev.c "$sdl"/src/core/linux/SDL_evdev_capabilities.c "$sdl"/src/core/linux/SDL_evdev_kbd.c
             "$sdl"/src/filesystem/unix/*.c
             "$sdl"/src/joystick/linux/*.c
             "$sdl"/src/locale/SDL_locale.c "$sdl"/src/locale/unix/*.c
             "$sdl"/src/misc/SDL_url.c "$sdl"/src/misc/unix/*.c
             "$sdl"/src/power/SDL_power.c "$sdl"/src/power/linux/*.c
             "$sdl"/src/process/SDL_process.c "$sdl"/src/process/posix/*.c
             "$sdl"/src/tray/SDL_tray_utils.c "$sdl"/src/tray/unix/*.c
             "$sdl"/src/video/x11/*.c "$sdl"/src/video/dummy/*.c "$sdl"/src/video/yuv2rgb/yuv_rgb_sse.c )
fi

cd "$root"
compile_list=$out_dir/sources.txt
: > "$compile_list"
for pattern in "${sources[@]}"; do
  for f in $pattern; do
    [[ -f "$f" ]] && echo "$f" >> "$compile_list" || true
  done
done

export CC="$cc" OUT="$out_dir" SDLDIR="$sdl"
mkdir -p "$out_dir/obj"
if [[ "$target" == android ]]; then
  # android hidapi backend is C++
  $cc -x c++ -c -O2 -fPIC -I"$OUT" -I"$SDLDIR/include" -I"$SDLDIR/src" \
    "$SDLDIR/src/hidapi/android/hid.cpp" -o "$OUT/obj/src_hidapi_android_hid.cpp.o"
fi
: > "$out_dir/objs.txt"
while read -r f; do
  obj="$out_dir/obj/$(echo "${f#"$sdl"/}" | tr '/' '_').o"
  echo "$obj $f" >> "$out_dir/objs.txt"
done < "$compile_list"

cat "$out_dir/objs.txt" | xargs -P "$(nproc)" -L1 sh -c '$CC -x c -c -O2 -fPIC -I"$OUT" -I"$SDLDIR/include" -I"$SDLDIR/src" "$2" -o "$1"' _

if [[ "$target" == android ]]; then
  rm -f "$out_dir/libSDL3.so"
  $cc -shared -Wl,-soname,libSDL3.so -o "$out_dir/libSDL3.so" "$out_dir"/obj/*.o \
    -llog -landroid -lEGL -lGLESv3 -ldl -lm -lc++_static -lc++abi
  echo "wrote $out_dir/libSDL3.so"
else
  rm -f "$out_dir/libSDL3.a"
  ar rcs "$out_dir/libSDL3.a" "$out_dir"/obj/*.o
  echo "wrote $out_dir/libSDL3.a"
fi
