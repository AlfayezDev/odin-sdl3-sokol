#!/usr/bin/env python3
"""Regeneration after editing shaders/app.slang; needs slangc.

Compiles the single Slang module per entry point to GLSL for sokol's GL
backend and embeds the sources as C strings in
app/native/shaders_generated.h (SHADER_VS_SRC / SHADER_FS_SRC /
SHADER_COMPUTE_SRC). The GLSL is emitted for GL 4.3 (storage buffer reads in
the fragment stage need #version 430).
"""
import os, pathlib, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'shaders/app.slang'
compiler = os.environ.get('SLANGC', 'slangc')
entry_points = [('SHADER_VS_SRC', 'vs_main', 'vertex'), ('SHADER_FS_SRC', 'ps_main', 'fragment'), ('SHADER_COMPUTE_SRC', 'cs_main', 'compute')]

def to_c_string(glsl: str) -> str:
    out = []
    for line in glsl.splitlines():
        out.append('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
    return '\n'.join(out)

parts = []
with tempfile.TemporaryDirectory() as tmp:
    for name, entry, stage in entry_points:
        output = pathlib.Path(tmp) / (stage + '.glsl')
        subprocess.run([compiler, str(source), '-entry', entry, '-stage', stage, '-target', 'glsl', '-o', str(output)], check=True)
        glsl = output.read_text()
        # sokol's GL core backend: ensure GL 4.6 for storage buffers + gl_BaseVertex
        import re as _re
        m = _re.search(r'#version (\d+)', glsl)
        if m:
            ver = int(m.group(1))
            if ver < 460:
                glsl = _re.sub(r'#version \d+', '#version 460', glsl, count=1)
        # Slang emits Vulkan GLSL builtin names; desktop GLSL differs:
        glsl = glsl.replace('gl_VertexIndex', 'gl_VertexID')
        glsl = glsl.replace('gl_BaseInstance', 'gl_BaseInstance')
        parts.append(f'static const char* {name} =\n{to_c_string(glsl)};\n')

header = '// Generated by scripts/shaders.py from shaders/app.slang. Do not edit.\n' + '\n'.join(parts)
(root / 'app/native/shaders_generated.h').write_text(header)
print('wrote app/native/shaders_generated.h')
