#!/usr/bin/env python3
"""Regeneration after editing shaders/app.slang; needs slangc.

Compiles the single Slang module per entry point to GLSL for sokol's GL
backends and embeds the sources as C strings in
app/native/shaders_generated.h: desktop GL (460) for SOKOL_GLCORE builds and
GLES (310 es) for SOKOL_GLES3 builds (Android); the shim picks via #if.
SLANGC and SPIRV_VAL environment variables override the tools.
"""
import os, pathlib, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'shaders/app.slang'
compiler = os.environ.get('SLANGC', 'slangc')
# name, entry, stage
entry_points = [
    ('SHADER_VS_SRC',       'vs_main', 'vertex'),
    ('SHADER_FS_SRC',       'ps_main', 'fragment'),
    ('SHADER_COMPUTE_SRC',  'cs_main', 'compute'),
]


def sokol_fold(glsl: str) -> str:
    """Slang emits Vulkan-style GLSL (separate texture2D + sampler opaques);
    sokol's GL/GLES backends need combined sampler2D declarations. Folds the
    one texture-sampler pair of this module into a single sampler2D."""
    import re
    mt = re.search(r'layout\(binding = (\d+)\)\s*uniform texture2D (\w+);', glsl)
    ms = re.search(r'layout\(binding = (\d+)\)\s*uniform sampler (\w+);', glsl)
    if not (mt and ms):
        return glsl
    tex_name, smp_name = mt.group(2), ms.group(2)
    binding = mt.group(1)
    combined = 'sokol_combined'
    glsl = re.sub(r'layout\(binding = \d+\)\s*uniform sampler \w+;\s*', '', glsl)
    glsl = re.sub(r'layout\(binding = \d+\)\s*uniform texture2D \w+;',
                  f'layout(binding = {binding}) uniform sampler2D {combined};', glsl, count=1)
    glsl = glsl.replace(f'sampler2D({tex_name},{smp_name})', combined)
    glsl = glsl.replace(f'sampler2D({tex_name}, {smp_name})', combined)
    glsl = glsl.replace(tex_name, combined)
    return glsl

def glesify(glsl: str) -> str:
    """Desktop GLSL 460 -> GLES 310 es for sokol's GLES3 backend."""
    import re
    glsl = re.sub(r'#version \d+(\s+core)?', '#version 310 es', glsl, count=1)
    # Slang lowers SV_VertexID to Vulkan builtins; GLES uses gl_VertexID
    # (vertexOffset is always 0 in this demo).
    glsl = re.sub(r'gl_VertexIndex\s*-\s*gl_BaseVertex', 'gl_VertexID', glsl)
    # GLES fragment shaders need an explicit default float precision.
    if 'precision highp float' not in glsl:
        glsl = glsl.replace('#version 310 es', '#version 310 es\nprecision highp float;', 1)
    # desktop-GL ARB extensions don't exist in GLES; `require` on a missing
    # extension fails the whole shader.
    glsl = re.sub(r'#extension GL_ARB_[^\n]*\n', '', glsl)
    # Mali's front-end rejects the two-operand #line form; strip the directives.
    glsl = re.sub(r'#line [^\n]*\n', '', glsl)
    return glsl

def to_c_string(glsl: str) -> str:
    out = []
    for line in glsl.splitlines():
        out.append('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
    return '\n'.join(out)

parts = []
with tempfile.TemporaryDirectory() as tmp:
    for name, entry, stage in entry_points:
        output = pathlib.Path(tmp) / (stage + '.glsl')
        subprocess.run([compiler, str(source), '-entry', entry, '-stage', stage, '-target', 'glsl', '-o', str(output)], check=True)
        glsl = output.read_text()
        import re
        # Slang's samplerless-texture extension doesn't exist in desktop GL /
        # GLES; texelFetch on a plain texture2D is core GLSL 430.
        glsl = re.sub(r'#extension GL_EXT_samplerless_texture_functions[^\n]*\n', '', glsl)
        glsl = sokol_fold(glsl)
        desktop = glsl
        # desktop GL: storage buffer reads need GL 4.3+; gl_BaseVertex is 4.6;
        # Slang emits Vulkan builtin names, desktop GLSL uses gl_VertexID
        m = re.search(r'#version (\d+)', glsl)
        if m and int(m.group(1)) < 460:
            desktop = re.sub(r'#version \d+', '#version 460', desktop, count=1)
        desktop = re.sub(r'gl_VertexIndex\s*-\s*gl_BaseVertex', 'gl_VertexID', desktop)
        parts.append(f'#ifndef SOKOL_GLES3\nstatic const char* {name} =\n{to_c_string(desktop)};\n#endif\n')
        gles = sokol_fold(glesify(glsl))
        parts.append(f'#ifdef SOKOL_GLES3\nstatic const char* {name}_GLES =\n{to_c_string(gles)};\n#endif\n')

header = '// Generated by scripts/shaders.py from shaders/app.slang. Do not edit.\n' + '\n'.join(parts)
(root / 'app/native/shaders_generated.h').write_text(header)
print('wrote app/native/shaders_generated.h')
