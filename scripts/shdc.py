#!/usr/bin/env python3
"""Regenerate shader headers after editing shaders/; needs sokol-shdc.

triangle.glsl -> app/native/triangle_shaders.h
shaders/samples/<name>.glsl -> app/native/sample_<name>_shaders.h, with every
generated identifier prefixed "<name>_" so all headers coexist in one TU.

Both headers carry a glsl410 variant (SHIM_GLCORE) and a glsl300es variant
(SHIM_GLES3), selected at compile time. SHDC overrides the tool path.
"""
import os, pathlib, re, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
shdc = os.environ.get('SHDC', str(root / 'vendors/tools/sokol-shdc'))

def gen(source, slang, out):
    subprocess.run([shdc, '-i', str(source), '-o', str(out), '-l', slang, '--format', 'sokol'], check=True)
    return out.read_text().replace('#pragma once\n', '')

def write_dual(header_path, glsl_source, prefix=None):
    with tempfile.TemporaryDirectory() as tmp:
        gl330 = gen(glsl_source, 'glsl410', pathlib.Path(tmp) / 'a.h')
        gles300 = gen(glsl_source, 'glsl300es', pathlib.Path(tmp) / 'b.h')
    if prefix:
        gl330, gles300 = prefix(gl330), prefix(gles300)
    body = ('// Generated by scripts/shdc.py. Do not edit.\n'
            '#if defined(SHIM_GLCORE)\n' + gl330
            + '#elif defined(SHIM_GLES3)\n' + gles300
            + '#endif\n')
    header_path.write_text(body)

write_dual(root / 'app/native/triangle_shaders.h', root / 'shaders/triangle.glsl')

def prefixed(body):
    """Prefix every generated identifier with the sample's name."""
    name = None  # set via closure below
    return body

def make_prefixer(name):
    def prefix(body):
        body = re.sub(r'\b((?:vs|fs)(?:_\w+)?_source_)', f'{name}_' + r'\1', body)
        for token in ('ATTR_', 'UB_', 'VIEW_', 'SMP_'):
            body = body.replace(token, f'{name}_{token}')
        body = re.sub(r'\b(?!sg_)(\w+)_shader_desc\b', f'{name}_' + r'\1_shader_desc', body)
        body = re.sub(r'\b(\w+_params_t)\b', f'{name}_' + r'\1', body)
        return body
    return prefix

for glsl in sorted((root / 'shaders/samples').glob('*.glsl')):
    name = glsl.stem
    write_dual(root / f'app/native/sample_{name}_shaders.h', glsl, make_prefixer(name))
    print(f'wrote app/native/sample_{name}_shaders.h')
