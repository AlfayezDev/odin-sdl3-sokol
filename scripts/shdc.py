#!/usr/bin/env python3
"""Regeneration after editing shaders/triangle.glsl; needs sokol-shdc.

Runs sokol-shdc twice (desktop GLSL 410 for SOKOL_GLCORE, GLES 300 es for
SOKOL_GLES3) and embeds both generated headers into
app/native/triangle_shaders.h, selected at compile time by the backend define
the platform shim sets. SHDC overrides the tool path.
"""
import os, pathlib, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'shaders/triangle.glsl'
shdc = os.environ.get('SHDC', str(root / 'vendors/tools/sokol-shdc'))
targets = [('triangle_gl330', 'glsl410'), ('triangle_gles300', 'glsl300es')]

parts = []
with tempfile.TemporaryDirectory() as tmp:
    for name, slang in targets:
        output = pathlib.Path(tmp) / (name + '.h')
        subprocess.run([shdc, '-i', str(source), '-o', str(output), '-l', slang, '--format', 'sokol'], check=True)
        body = output.read_text()
        # strip the duplicated include guard; keep the content
        body = body.replace('#pragma once\n', '')
        parts.append(f'#if defined({name.upper()})\n{body}\n#endif\n')

header = ('// Generated by scripts/shdc.py from shaders/triangle.glsl via sokol-shdc. Do not edit.\n'
          + '\n'.join(parts))
(root / 'app/native/triangle_shaders.h').write_text(header)
print('wrote app/native/triangle_shaders.h')
