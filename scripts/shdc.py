#!/usr/bin/env python3
"""Regenerate shader bindings after editing shaders/; needs sokol-shdc.

shaders/samples/<name>.glsl -> vendors/shaders/<name>.odin
(package shaders, import sg "libs:sg"): one sokol-shdc run per backend
(glsl410 / glsl300es, shdc's odin output only carries a single slang) plus a
dispatch proc per program named <name>_<prog>_shader_desc(backend). All
generated identifiers are prefixed "<name>_" so the files coexist in one
package. SHDC overrides the tool path.
"""
import os, pathlib, re, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
shdc = os.environ.get('SHDC', str(root / 'vendors/tools/sokol-shdc'))

def make_prefixer(prefix):
    def prefixer(body):
        body = re.sub(r'\b((?:vs|fs)(?:_\w+)?_source_)', f'{prefix}_' + r'\1', body)
        for token in ('ATTR_', 'UB_', 'VIEW_', 'SMP_'):
            body = body.replace(token, f'{prefix}_{token}')
        body = re.sub(r'\b([A-Z]\w*_Params)\b', f'{prefix}_' + r'\1', body)
        body = re.sub(r'\b(?!sg_)(\w+)_shader_desc\b', f'{prefix}_' + r'\1_shader_desc', body)
        return body
    return prefixer

def gen_odin(glsl, slang, out):
    subprocess.run([shdc, '-i', str(glsl), '-o', str(out), '-l', slang, '--format', 'sokol_odin'], check=True)
    return out.read_text()

def patch_array_count(text):
    # sokol-gfx validation requires array_count > 0; shdc emits 0 for scalars
    return text.replace('.array_count = 0', '.array_count = 1').replace('.array_count = 0;', '.array_count = 1;')

def write_sample(glsl):
    name = glsl.stem
    with tempfile.TemporaryDirectory() as tmp:
        gl4 = gen_odin(glsl, 'glsl410', pathlib.Path(tmp) / 'a.odin')
        gles = gen_odin(glsl, 'glsl300es', pathlib.Path(tmp) / 'b.odin')
    gl4 = patch_array_count(make_prefixer(f'{name}_gl4')(gl4))
    gles = patch_array_count(make_prefixer(name)(gles))
    # suffix the gles3 desc procs so the dispatch proc can take the plain name
    progs = re.findall(rf'\b{name}_(\w+)_shader_desc :: proc', gles)
    for prog in progs:
        gles = gles.replace(f'{name}_{prog}_shader_desc :: proc', f'{name}_{prog}_shader_desc_gles3 :: proc')
    dispatch = '\n'.join(
        f'{name}_{prog}_shader_desc :: proc "c" (backend: sg.Backend) -> sg.Shader_Desc {{\n'
        f'\t#partial switch backend {{\n'
        f'\tcase .GLES3:\n'
        f'\t\treturn {name}_{prog}_shader_desc_gles3(backend)\n'
        f'\tcase .GLCORE:\n'
        f'\t\treturn {name}_gl4_{prog}_shader_desc(backend)\n'
        f'\t}}\n'
        f'\treturn {{}}\n'
        f'}}' for prog in progs)
    header = (f'// Generated by scripts/shdc.py from {glsl.name} via sokol-shdc. Do not edit.\n'
              'package shaders\n\nimport sg "libs:sg"\n\n'
              + gl4 + '\n' + gles + '\n' + dispatch + '\n')
    (root / 'vendors/shaders' / f'{name}.odin').write_text(header)
    print(f'wrote vendors/shaders/{name}.odin ({len(progs)} programs)')

shaders_dir = root / 'vendors/shaders'
shaders_dir.mkdir(exist_ok=True)
for old in shaders_dir.glob('*.odin'):
    old.unlink()
for glsl in sorted((root / 'shaders/samples').glob('*.glsl')):
    write_sample(glsl)
